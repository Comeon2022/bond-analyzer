export function getCoreCardSummary(card: CoreCardInput): string {
  if (card.status === 'unknown' || card.value === null) {
    return unavailableCopy[card.key] ?? 'אין מספיק נתונים עדכניים כדי להסביר את המדד.';
  }
  return summaries[card.key]?.[card.status]?.(card.value)
    ?? 'הנתונים זמינים, אך אין כרגע איתות ברור לגבי משמעותם לשוק האג״ח.';
}
